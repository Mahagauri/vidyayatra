/**
 * Rolls a random figure from the roster.
 * Biased towards figures not yet unlocked by the user to ensure exciting progress,
 * with weighted probabilities for rarity tiers.
 */
export function rollRandomFigure(unlockedIds: string[]): MythologicalFigure {
  const unlockedSet = new Set(unlockedIds);
  const undiscovered = MYTHOLOGICAL_FIGURES.filter((f) => !unlockedSet.has(f.id));

  // If there are still undiscovered figures, prioritize them (90% chance)
  const pool = (undiscovered.length > 0 && Math.random() < 0.9)
    ? undiscovered
    : MYTHOLOGICAL_FIGURES;

  const totalWeight = pool.reduce((acc, curr) => acc + curr.rarityWeight, 0);
  let random = Math.random() * totalWeight;

  for (const figure of pool) {
    if (random < figure.rarityWeight) {
      return figure;
    }
    random -= figure.rarityWeight;
  }

  return pool[0] || MYTHOLOGICAL_FIGURES[0];
}
